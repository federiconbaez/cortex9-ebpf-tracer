#!/usr/bin/env python3
"""Regenerate the syscall and errno tables from Linux UAPI headers.

Usage: scripts/gen_tables.py [INCLUDE_DIR]   (default: /usr/include)

Writes cortex9-tracer/src/syscalls/{x86_64,aarch64}.rs and
cortex9-tracer/src/errno_table.rs. Needs `cpp` for the asm-generic table.
"""
import os
import re
import subprocess
import sys
import tempfile

INC = sys.argv[1] if len(sys.argv) > 1 else "/usr/include"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "cortex9-tracer", "src")
HEADER = "// @generated by scripts/gen_tables.py from Linux UAPI headers. Do not edit.\n"


def x86_64():
    path = os.path.join(INC, "x86_64-linux-gnu", "asm", "unistd_64.h")
    if not os.path.exists(path):
        path = os.path.join(INC, "asm", "unistd_64.h")
    table = {}
    for line in open(path):
        m = re.match(r"#define __NR_(\w+)\s+(\d+)\s*$", line)
        if m:
            table[int(m.group(2))] = m.group(1)
    return table


def aarch64():
    # arm64 uses the asm-generic numbering with these feature macros.
    flags = [
        "-D__BITS_PER_LONG=64",
        "-D__ARCH_WANT_RENAMEAT",
        "-D__ARCH_WANT_NEW_STAT",
        "-D__ARCH_WANT_SET_GET_RLIMIT",
        "-D__ARCH_WANT_TIME32_SYSCALLS",
        "-D__ARCH_WANT_SYS_CLONE3",
        "-D__ARCH_WANT_MEMFD_SECRET",
    ]
    src = "#include <asm-generic/unistd.h>\n"
    with tempfile.TemporaryDirectory() as stub:
        # asm-generic/unistd.h includes <asm/bitsperlong.h>; the value is
        # already forced with -D__BITS_PER_LONG=64.
        os.makedirs(os.path.join(stub, "asm"))
        open(os.path.join(stub, "asm", "bitsperlong.h"), "w").close()
        out = subprocess.run(
            ["cpp", "-dM", "-nostdinc", "-I", stub, "-I", INC] + flags,
            input=src, capture_output=True, text=True, check=True,
        ).stdout
    defs = {}
    for line in out.splitlines():
        m = re.match(r"#define (__NR\w+) (.+)$", line)
        if m:
            defs[m.group(1)] = m.group(2).strip()

    def resolve(v, depth=0):
        if depth > 8:
            return None
        if re.fullmatch(r"\d+", v):
            return int(v)
        if v in defs:
            return resolve(defs[v], depth + 1)
        return None

    table = {}
    for k, v in defs.items():
        if not k.startswith("__NR_") or k in ("__NR_syscalls",):
            continue
        n = resolve(v)
        if n is not None:
            table.setdefault(n, k[len("__NR_"):])
    return table


def errnos():
    table = {}
    for name in ("errno-base.h", "errno.h"):
        for line in open(os.path.join(INC, "asm-generic", name)):
            m = re.match(r"#define\s+(E\w+)\s+(\d+)\b", line)
            if m:
                table.setdefault(int(m.group(2)), m.group(1))
    return table


def emit(path, const, table, doc):
    width = max(table) + 1
    with open(path, "w") as f:
        f.write(HEADER)
        f.write(f"\n/// {doc}\n")
        f.write(f"pub(super) const {const}: [Option<&str>; {width}] = [\n")
        for i in range(width):
            v = table.get(i)
            f.write(f'    Some("{v}"),\n' if v else "    None,\n")
        f.write("];\n")


emit(os.path.join(OUT, "syscalls", "x86_64.rs"), "TABLE", x86_64(),
     "x86_64 syscall names indexed by number (asm/unistd_64.h).")
emit(os.path.join(OUT, "syscalls", "aarch64.rs"), "TABLE", aarch64(),
     "aarch64 syscall names indexed by number (asm-generic/unistd.h).")
emit(os.path.join(OUT, "errno_table.rs"), "ERRNO", errnos(),
     "errno names indexed by value (asm-generic/errno*.h).")
